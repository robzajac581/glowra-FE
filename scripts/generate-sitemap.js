#!/usr/bin/env node
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const BLOG_JSON_PATH = path.join(ROOT, "src", "generated", "blog-content.json");
const PUBLIC_DIR = path.join(ROOT, "public");
const SITEMAP_PATH = path.join(PUBLIC_DIR, "sitemap.xml");
const ROBOTS_PATH = path.join(PUBLIC_DIR, "robots.txt");

const defaultSiteUrl = "https://www.glowra.com";
const siteUrl = (process.env.REACT_APP_SITE_URL || defaultSiteUrl).replace(/\/+$/, "");

const readBlogPosts = () => {
	if (!fs.existsSync(BLOG_JSON_PATH)) {
		return [];
	}

	return JSON.parse(fs.readFileSync(BLOG_JSON_PATH, "utf8"));
};

const toUrlEntry = ({ pathName, lastMod }) => {
	const normalizedPath = pathName.startsWith("/") ? pathName : `/${pathName}`;
	return `
  <url>
    <loc>${siteUrl}${normalizedPath}</loc>
    <lastmod>${lastMod}</lastmod>
  </url>`;
};

// AI crawler policy (GLO-103): allow search/retrieval and training bots so
// Glowra can be found and cited by AI assistants. /admin is blocked for every
// bot. A named group replaces the "*" group for that bot, so each group repeats
// the /admin rule. To opt out of a bot, change its "Allow: /" to "Disallow: /".
const AI_CRAWLERS = [
	"GPTBot", // OpenAI training
	"OAI-SearchBot", // ChatGPT search index
	"ChatGPT-User", // ChatGPT fetching a page for a user
	"ClaudeBot", // Anthropic training
	"Claude-SearchBot", // Claude search index
	"Claude-User", // Claude fetching a page for a user
	"PerplexityBot", // Perplexity search index
	"Perplexity-User", // Perplexity fetching a page for a user
	"Google-Extended", // Gemini / AI training (does not affect Google Search)
];

const buildRobots = (baseUrl) => {
	const groups = [
		"User-agent: *\nDisallow: /admin",
		...AI_CRAWLERS.map((bot) => `User-agent: ${bot}\nAllow: /\nDisallow: /admin`),
	];
	return `# https://www.robotstxt.org/robotstxt.html
# Generated by scripts/generate-sitemap.js; edit there, not here.
# AI crawlers are welcome. See ${baseUrl}/llms.txt

${groups.join("\n\n")}

Sitemap: ${baseUrl}/sitemap.xml
`;
};

const run = () => {
	const nowIso = new Date().toISOString();
	const blogPosts = readBlogPosts();

	const coreRoutes = [
		{ pathName: "/", lastMod: nowIso },
		{ pathName: "/search", lastMod: nowIso },
		{ pathName: "/blog", lastMod: nowIso },
	];

	const blogRoutes = blogPosts.map((post) => ({
		pathName: `/blog/${post.slug}`,
		lastMod: new Date(post.date).toISOString(),
	}));

	const entries = [...coreRoutes, ...blogRoutes].map(toUrlEntry).join("");

	const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">${entries}
</urlset>
`;

	const robots = buildRobots(siteUrl);

	fs.mkdirSync(PUBLIC_DIR, { recursive: true });
	fs.writeFileSync(SITEMAP_PATH, sitemap, "utf8");
	fs.writeFileSync(ROBOTS_PATH, robots, "utf8");

	console.log(`Generated sitemap with ${coreRoutes.length + blogRoutes.length} URL(s)`);
};

run();
